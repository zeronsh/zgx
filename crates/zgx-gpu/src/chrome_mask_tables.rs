//! Chrome's glyph coverage tables on macOS: what Skia does to the mask Core
//! Text draws before it blends the text (a four-way split by the text's
//! luminance, `lum >> 6`): measured from Chrome's own pixels for black to
//! white text, a gentle thinning for dark text and a strong firming for
//! light text, so it blends in sRGB as Chrome's does.

/// The table for luminance bucket `bucket` (0 to 3).
pub(crate) fn for_luminance_bucket(bucket: u8) -> &'static [u8; 256] {
    &TABLES[usize::from(bucket & 3)]
}

/// The luminance bucket of text coloured `rgb`, as Chrome's Skia takes it:
/// each channel to its top three bits (spread back over 0 to 255), weighted
/// as Rec. 709 luma, in fours.
pub(crate) fn bucket_of(rgb: [u8; 3]) -> u8 {
    let spread = |c: u8| {
        let bits = u32::from(c >> 5);
        (bits << 5) | (bits << 2) | (bits >> 1)
    };
    let [r, g, b] = rgb.map(spread);
    let luma = (2126 * r + 7152 * g + 722 * b) / 10_000;
    (luma >> 6).min(3) as u8
}

