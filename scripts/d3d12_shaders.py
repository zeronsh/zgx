#!/usr/bin/env python3
"""Regenerate draw.wgsl's six Direct3D 12 FXC stages on Windows.

python scripts/d3d12_shaders.py          # generate, then rebuild and check
python scripts/d3d12_shaders.py --check  # check existing bytecode only

The generator test uses the same HLSL translation/layout as wgpu-hal and
FXC's strict flag, shader model 5.1, without DEBUG. Missing include files
are bootstrapped locally for the generator compilation only; empty files
are never valid output, and are removed if generation fails.
"""

import argparse
import hashlib
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / "crates/zgx-gpu/src/dx12"
ENTRIES = ("vs", "vs_basic", "fs", "fs_both", "fs_basic", "fs_basic_both")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if os.name != "nt":
        sys.exit("FXC generation and checking require Windows")
    paths = [DIRECTORY / f"draw_{entry}.dxbc" for entry in ENTRIES]
    created = []
    command = ["cargo", "test", "--release", "-p", "zgx-gpu", "--lib", "--locked",
               "dx12_precompiled::tests::precompiled_shaders_match", "--", "--exact"]
    env = dict(os.environ)
    env.pop("ZGX_BLESS", None)
    try:
        if not args.check:
            DIRECTORY.mkdir(parents=True, exist_ok=True)
            for path in paths:
                if not path.exists():
                    path.write_bytes(b"")
                    created.append(path)
            subprocess.run(command, cwd=ROOT, env=dict(env, ZGX_BLESS="1"), check=True)
        for path in paths:
            if not path.is_file() or path.stat().st_size == 0:
                sys.exit(f"Missing generated bytecode: {path}")
        # Rebuild after blessing so include_bytes sees the generated files.
        subprocess.run(command, cwd=ROOT, env=env, check=True)
        for path in paths:
            data = path.read_bytes()
            print(f"{hashlib.sha256(data).hexdigest()}  {path.relative_to(ROOT).as_posix()}  {len(data)} B")
    finally:
        for path in created:
            if path.exists() and path.stat().st_size == 0:
                path.unlink()


if __name__ == "__main__":
    main()
